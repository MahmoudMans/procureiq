/*
 * Historical compatibility callback.
 *
 * V13 and V34 accidentally use the same relation name for two unrelated
 * domain models:
 *
 * V13:
 *   supplier_compliance_documents
 *   -> contract/compliance evidence
 *
 * V34:
 *   supplier_compliance_documents
 *   -> document-vault authority
 *
 * The callback temporarily moves V13 aside immediately after V13 succeeds.
 * No migrations V14-V33 reference this relation.
 *
 * Immediately after V34 succeeds, the V34 table is moved to:
 *
 *   supplier_document_vault_documents
 *
 * and the original V13 table is restored to:
 *
 *   supplier_compliance_documents
 *
 * Historical V13 and V34 migration files remain unchanged.
 */

DO $$
DECLARE
    old_exists BOOLEAN;

    temp_exists BOOLEAN;

    vault_exists BOOLEAN;

    old_has_contract_id BOOLEAN := FALSE;

    old_has_requirement_id BOOLEAN := FALSE;

    temp_has_contract_id BOOLEAN := FALSE;
BEGIN
    old_exists :=
        to_regclass(
            current_schema()
            || '.supplier_compliance_documents'
        ) IS NOT NULL;

    temp_exists :=
        to_regclass(
            current_schema()
            || '.supplier_compliance_documents_v13_legacy'
        ) IS NOT NULL;

    vault_exists :=
        to_regclass(
            current_schema()
            || '.supplier_document_vault_documents'
        ) IS NOT NULL;


    IF old_exists THEN
        SELECT EXISTS (
            SELECT 1

            FROM information_schema.columns

            WHERE table_schema =
                current_schema()

            AND table_name =
                'supplier_compliance_documents'

            AND column_name =
                'contract_id'
        )
        INTO old_has_contract_id;


        SELECT EXISTS (
            SELECT 1

            FROM information_schema.columns

            WHERE table_schema =
                current_schema()

            AND table_name =
                'supplier_compliance_documents'

            AND column_name =
                'requirement_id'
        )
        INTO old_has_requirement_id;
    END IF;


    IF temp_exists THEN
        SELECT EXISTS (
            SELECT 1

            FROM information_schema.columns

            WHERE table_schema =
                current_schema()

            AND table_name =
                'supplier_compliance_documents_v13_legacy'

            AND column_name =
                'contract_id'
        )
        INTO temp_has_contract_id;
    END IF;


    /*
     * Migrations before V13.
     */
    IF
        NOT old_exists
        AND
        NOT temp_exists
        AND
        NOT vault_exists
    THEN
        RETURN;
    END IF;


    /*
     * Immediately after V13.
     *
     * Move legacy relation aside and free the autogenerated PK relation name
     * required by V34.
     */
    IF
        old_exists
        AND
        old_has_contract_id
        AND
        NOT old_has_requirement_id
        AND
        NOT temp_exists
        AND
        NOT vault_exists
    THEN
        EXECUTE
            'ALTER TABLE supplier_compliance_documents '
            'RENAME TO supplier_compliance_documents_v13_legacy';

        IF EXISTS (
            SELECT 1

            FROM pg_constraint

            WHERE conrelid =
                'supplier_compliance_documents_v13_legacy'::regclass

            AND conname =
                'supplier_compliance_documents_pkey'
        ) THEN
            EXECUTE
                'ALTER TABLE supplier_compliance_documents_v13_legacy '
                'RENAME CONSTRAINT supplier_compliance_documents_pkey '
                'TO supplier_compliance_documents_v13_legacy_pkey';
        END IF;

        RETURN;
    END IF;


    /*
     * Between V14 and V33.
     */
    IF
        NOT old_exists
        AND
        temp_exists
        AND
        temp_has_contract_id
        AND
        NOT vault_exists
    THEN
        RETURN;
    END IF;


    /*
     * Immediately after V34.
     *
     * Old name now belongs to V34.
     */
    IF
        old_exists
        AND
        old_has_requirement_id
        AND
        NOT old_has_contract_id
        AND
        temp_exists
        AND
        temp_has_contract_id
        AND
        NOT vault_exists
    THEN
        EXECUTE
            'ALTER TABLE supplier_compliance_documents '
            'RENAME TO supplier_document_vault_documents';


        IF EXISTS (
            SELECT 1

            FROM pg_constraint

            WHERE conrelid =
                'supplier_document_vault_documents'::regclass

            AND conname =
                'supplier_compliance_documents_pkey'
        ) THEN
            EXECUTE
                'ALTER TABLE supplier_document_vault_documents '
                'RENAME CONSTRAINT supplier_compliance_documents_pkey '
                'TO supplier_document_vault_documents_pkey';
        END IF;


        IF EXISTS (
            SELECT 1

            FROM pg_trigger

            WHERE tgrelid =
                'supplier_document_vault_documents'::regclass

            AND tgname =
                'trg_audit_supplier_compliance_documents'

            AND NOT tgisinternal
        ) THEN
            EXECUTE
                'ALTER TRIGGER trg_audit_supplier_compliance_documents '
                'ON supplier_document_vault_documents '
                'RENAME TO trg_audit_supplier_document_vault_documents';
        END IF;


        EXECUTE
            'ALTER TABLE supplier_compliance_documents_v13_legacy '
            'RENAME TO supplier_compliance_documents';


        IF EXISTS (
            SELECT 1

            FROM pg_constraint

            WHERE conrelid =
                'supplier_compliance_documents'::regclass

            AND conname =
                'supplier_compliance_documents_v13_legacy_pkey'
        ) THEN
            EXECUTE
                'ALTER TABLE supplier_compliance_documents '
                'RENAME CONSTRAINT supplier_compliance_documents_v13_legacy_pkey '
                'TO supplier_compliance_documents_pkey';
        END IF;

        RETURN;
    END IF;


    /*
     * Normalized state after V34.
     */
    IF
        old_exists
        AND
        old_has_contract_id
        AND
        NOT old_has_requirement_id
        AND
        vault_exists
        AND
        NOT temp_exists
    THEN
        RETURN;
    END IF;


    RAISE EXCEPTION
        'Unexpected supplier compliance document authority state: '
        'old_exists=%, temp_exists=%, vault_exists=%, '
        'old_has_contract_id=%, old_has_requirement_id=%, '
        'temp_has_contract_id=%',
        old_exists,
        temp_exists,
        vault_exists,
        old_has_contract_id,
        old_has_requirement_id,
        temp_has_contract_id;
END;
$$;
